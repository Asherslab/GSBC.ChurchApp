#!/usr/bin/env python3
"""Compare a publish log's trim/AOT warnings against a committed baseline of known library warnings.

    check.py <publish.log> <baseline.txt> --ours Contracts. Server. [--update]

Fails when:
  - a warning comes from our own code (a source path in this repo, or a member under one of --ours):
    ours are fixed or suppressed in source with [UnconditionalSuppressMessage] and a justification,
    never baselined;
  - a library warning is not in the baseline (a new reflection path, usually after an upgrade);
  - a baseline entry no longer appears (fixed upstream: prune it, so the list stays exact).

--update rewrites the baseline from the log (library warnings only) instead of checking.
"""
import argparse
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# "<path>(<line>): Trim analysis warning IL2026: Member: message [project]"  or  "ILLink : ... warning IL2111: ..."
LINE = re.compile(r"^\s*(?P<src>.*?)\s*:\s*(?:Trim|AOT) analysis warning (?P<code>IL\d{4}): (?P<text>.*?)(?: \[[^\]]*\])?\s*$")


def warnings(log_path):
    found = {}
    with open(log_path, encoding="utf-8", errors="replace") as log:
        for raw in log:
            m = LINE.match(raw)
            if not m:
                continue
            src = re.sub(r"\(\d+(,\d+)?\)$", "", m["src"])  # line numbers move; members don't
            key = f"{m['code']}: {m['text']}"
            found.setdefault(key, src)
    return found


def is_ours(key, src, prefixes):
    member = key.split(": ", 1)[1]
    return src.startswith(REPO) or any(member.startswith(p) for p in prefixes)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("log")
    ap.add_argument("baseline")
    ap.add_argument("--ours", nargs="*", default=[])
    ap.add_argument("--update", action="store_true")
    a = ap.parse_args()

    with open(a.log, encoding="utf-8", errors="replace") as log:
        if re.search(r": error [A-Z]+\d+:", log.read()):
            print(f"{a.log} records a failed build; fix that first.")
            return 2

    found = warnings(a.log)
    ours = sorted(k for k, src in found.items() if is_ours(k, src, a.ours))
    library = sorted(k for k, src in found.items() if not is_ours(k, src, a.ours))

    if ours:
        print(f"{len(ours)} warning(s) in our own code. Fix them, or suppress in source with a justification:")
        print("\n".join(f"  {k}" for k in ours))

    if a.update:
        with open(a.baseline, "w", encoding="utf-8") as f:
            f.write("# Known trim/AOT warnings from library code. Generated by check.py --update; review the diff.\n")
            f.write("\n".join(library) + "\n")
        print(f"Wrote {len(library)} library warning(s) to {a.baseline}")
        return 1 if ours else 0

    with open(a.baseline, encoding="utf-8") as f:
        known = {l.rstrip("\n") for l in f if l.strip() and not l.startswith("#")}
    new = [k for k in library if k not in known]
    gone = sorted(known - set(library))
    if new:
        print(f"{len(new)} new library warning(s) not in {os.path.basename(a.baseline)}:")
        print("\n".join(f"  {k}" for k in new))
    if gone:
        print(f"{len(gone)} baseline entr(y/ies) no longer reported; prune them:")
        print("\n".join(f"  {k}" for k in gone))
    if not (ours or new or gone):
        print(f"OK: {len(library)} known library warning(s), none new, none in our code.")
    return 1 if (ours or new or gone) else 0


if __name__ == "__main__":
    sys.exit(main())
