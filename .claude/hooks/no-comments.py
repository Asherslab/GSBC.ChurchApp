#!/usr/bin/env python3
import json
import os
import re
import sys

SLASH = {".cs", ".js", ".mjs", ".ts", ".swift", ".kt", ".kts", ".java", ".css", ".scss"}
MARKUP = {".html", ".xml", ".csproj", ".props", ".targets", ".config", ".xaml"}
HASH = {".py", ".sh", ".yml", ".yaml", ".toml", ".ps1"}
RAZOR = {".razor", ".cshtml"}

ALLOWED = re.compile(r"<auto-generated|#!|#nullable|#pragma|#region|#endregion|eslint-|@ts-|ReSharper disable|swiftlint:")


def comment_patterns(ext):
    slash = [r"^\s*(//|/\*)", r"\S\s+(//|/\*)\s"]
    if ext in SLASH:
        return slash
    if ext in RAZOR:
        return slash + [r"@\*", r"<!--"]
    if ext in MARKUP:
        return [r"<!--"]
    if ext in HASH:
        return [r"^\s*#(?!!)", r"\S\s+#\s"]
    return []


def added_lines(tool, inp):
    if tool == "Write":
        return inp.get("content", "").splitlines()
    edits = inp.get("edits") if tool == "MultiEdit" else [inp]
    lines = []
    for edit in edits or []:
        before = set(edit.get("old_string", "").splitlines())
        lines += [l for l in edit.get("new_string", "").splitlines() if l not in before]
    return lines


def main():
    event = json.load(sys.stdin)
    path = event.get("tool_input", {}).get("file_path", "")
    ext = os.path.splitext(path)[1].lower()
    patterns = [re.compile(p) for p in comment_patterns(ext)]
    if not patterns:
        return 0

    found = [l.strip() for l in added_lines(event.get("tool_name", ""), event.get("tool_input", {}))
             if any(p.search(l) for p in patterns) and not ALLOWED.search(l)]
    if not found:
        return 0

    shown = "\n".join(f"  {l[:160]}" for l in found[:20])
    more = f"\n  ... and {len(found) - 20} more" if len(found) > 20 else ""
    print(
        f"Comments added to {os.path.basename(path)}:\n{shown}{more}\n\n"
        "Project rule (AGENTS.md, Comments): no comments unless the code cannot be understood without them. "
        "Make the code say it instead (names, smaller methods, types, named constants) and delete these. "
        "A comment may stay only if it records something the code cannot show, such as why a non-obvious "
        "choice was made or an external constraint, and then say in your reply which one you kept and why.",
        file=sys.stderr,
    )
    return 2


if __name__ == "__main__":
    sys.exit(main())
