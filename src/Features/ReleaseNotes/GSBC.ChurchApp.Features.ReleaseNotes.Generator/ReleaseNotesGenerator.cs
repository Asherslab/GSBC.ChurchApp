using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace GSBC.ChurchApp.Features.ReleaseNotes.Generator;

[Generator]
public sealed class ReleaseNotesGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor BadNote = new(
        "GSBCRN01", "Release note can't be read", "{0}: {1}", "ReleaseNotes", DiagnosticSeverity.Error, isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor BadAudience = new(
        "GSBCRN02", "Release notes audience is wrong", "{0}", "ReleaseNotes", DiagnosticSeverity.Error, isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<(AdditionalText File, string? Kind)> marked = context.AdditionalTextsProvider
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Select((pair, _) => (pair.Left, pair.Right.GetOptions(pair.Left).TryGetValue("build_metadata.AdditionalFiles.GsbcReleaseNote", out string? kind) ? kind : null));

        IncrementalValuesProvider<NoteSource> notes = marked
            .Where(file => file.Kind == "note")
            .Select((file, cancellation) => new NoteSource(
                file.File.Path,
                Path.GetFileName(Path.GetDirectoryName(file.File.Path)) ?? "",
                Path.GetFileName(file.File.Path),
                file.File.GetText(cancellation)?.ToString() ?? ""));

        IncrementalValuesProvider<string> images = marked
            .Where(file => file.Kind == "image")
            .Select((file, _) => Path.GetFileName(file.File.Path));

        IncrementalValueProvider<string?> audience = context.AnalyzerConfigOptionsProvider
            .Select((options, _) => options.GlobalOptions.TryGetValue("build_property.GsbcReleaseNotes", out string? value) ? value : null);

        context.RegisterSourceOutput(notes.Collect().Combine(images.Collect()).Combine(audience),
            (production, input) => Emit(production, input.Left.Left, input.Left.Right, input.Right));
    }

    private sealed record NoteSource(string Path, string Folder, string Name, string Text);

    private static void Emit(SourceProductionContext context, ImmutableArray<NoteSource> files, ImmutableArray<string> images, string? audienceProperty)
    {
        NoteAudience build;
        try
        {
            build = BuildNotes.AudienceOf(audienceProperty);
        }
        catch (NoteException problem)
        {
            context.ReportDiagnostic(Diagnostic.Create(BadAudience, Location.None, problem.Message));
            return;
        }

        List<Note> notes = [];
        foreach (NoteSource file in files)
        {
            try
            {
                Note note = NoteFile.Parse(file.Folder, file.Name, file.Text);
                if (note.Image is not null && !images.Contains(note.Image))
                    throw new NoteException($"put the image \"{note.Image}\" in changelog/images/");
                notes.Add(note);
            }
            catch (NoteException problem)
            {
                context.ReportDiagnostic(Diagnostic.Create(BadNote, Location.Create(file.Path, default, default), file.Path, problem.Message));
            }
        }

        foreach (IGrouping<string, Note> twice in notes.GroupBy(note => note.Id).Where(group => group.Count() > 1))
            context.ReportDiagnostic(Diagnostic.Create(BadNote, Location.None, twice.Key, "two notes share this file name; rename one"));

        context.AddSource("BundledReleaseNotes.g.cs", SourceText.From(Render(build, BuildNotes.For(build, notes)), Encoding.UTF8));
    }

    public static string Render(NoteAudience build, IReadOnlyList<Note> notes)
    {
        StringBuilder source = new();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("namespace GSBC.ChurchApp.Features.ReleaseNotes.App;");
        source.AppendLine();
        source.AppendLine("internal static class BundledReleaseNotes");
        source.AppendLine("{");
        source.AppendLine($"    public const bool ForStaff = {(build == NoteAudience.Staff ? "true" : "false")};");
        source.AppendLine();
        source.AppendLine("    public static global::System.Collections.Generic.IReadOnlyList<ReleaseNote> All { get; } =");
        source.AppendLine("    [");
        foreach (Note note in notes)
        {
            source.AppendLine(
                $"        new({Literal(note.Id)}, {Literal(note.Version)}, {Literal(note.Title)}, {Literal(note.Summary)}, " +
                $"{(note.Highlight ? "true" : "false")}, {(note.Audience == NoteAudience.Staff ? "true" : "false")}, " +
                $"{Literal(note.Icon)}, {Literal(note.Link)}, {Literal(note.Image)}, {Literal(note.Area)}, " +
                $"{Literal(note.Changed)}, {Literal(note.Where)}, {Literal(note.Try)}),");
        }
        source.AppendLine("    ];");
        source.AppendLine("}");
        return source.ToString();
    }

    private static string Literal(string? value) => value is null ? "null" : SymbolDisplay.FormatLiteral(value, quote: true);
}
