import { chromium } from 'playwright-core';
import { readdirSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
const [,, script, ...rest] = process.argv;
const dir = join(homedir(), '.cache', 'gsbc-look-check');
const session = join(dir, readdirSync(dir).filter(f => f.endsWith('.session.json')).map(f => f).sort().pop());
const width = Number(process.env.W ?? 1440), height = Number(process.env.H ?? 900);
const browser = await chromium.launch();
const context = await browser.newContext({ storageState: process.env.SESSION ?? session, viewport: { width, height }, colorScheme: process.env.SCHEME ?? 'light', acceptDownloads: true });
const page = await context.newPage();
page.on('console', m => { if (m.type() === 'error') console.log('console error:', m.text().slice(0, 300)); });
page.on('pageerror', e => console.log('page error:', e.message.slice(0, 300)));
const base = process.env.BASE ?? 'http://localhost:5700';
const out = process.env.OUT;
const shot = async name => { await page.waitForTimeout(400); await page.screenshot({ path: `${out}/${name}.png` }); console.log('shot', name); };
const go = async path => { await page.goto(base + path); await page.waitForLoadState('networkidle').catch(() => {}); await page.waitForTimeout(1500); };
const run = (await import(script)).default;
try { await run({ page, go, shot, base, out, args: rest }); } catch (e) { console.log('failed:', e.message); await shot('failure'); }
await browser.close();
